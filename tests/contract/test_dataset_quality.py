"""Contract tests over the *produced* dataset files (specs/002 contracts/dataset-preparation.md).

They skip until data/dataset_report.json exists — i.e. until the dataset has been regenerated
by the 002 pipeline (tasks.md T037) — so the suite stays green on the feature-001 data files,
which are known to contain exactly the defects these tests forbid.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

import pytest

from src.dataset_filters.quality import is_degenerate_output
from src.prepare_dataset import MIN_PER_CATEGORY, TARGET_TOTAL_MAX, TARGET_TOTAL_MIN, _combined_text, _load_eval_prompt_keys
from src.schema_validation import TASK_CATEGORIES
from src.text_normalize import normalize

DATA_DIR = Path("data")
REPORT = DATA_DIR / "dataset_report.json"

_PREVISAO = re.compile(r"previs", re.IGNORECASE)
_CODE_TERMS = re.compile(r"\b(código|code|programa|função|script|sql|python|javascript|bug)\b", re.IGNORECASE)
_TRIVIA = re.compile(r"curiosidade", re.IGNORECASE)


def _load(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


@pytest.fixture(scope="module")
def produced():
    if not REPORT.exists():
        pytest.skip("data/dataset_report.json absent — dataset not yet regenerated by the 002 pipeline (T037)")
    train = _load(DATA_DIR / "train.jsonl")
    validation = _load(DATA_DIR / "validation.jsonl")
    report = json.loads(REPORT.read_text(encoding="utf-8"))
    return train, validation, report


def test_grammar_rows_have_no_forecast_or_code_instructions(produced):
    train, validation, _ = produced
    grammar = [r for r in train + validation if r["task_category"] == "grammar_correction"]
    assert not [r["id"] for r in grammar if _PREVISAO.search(r["instruction"])]
    assert not [r["id"] for r in grammar if _CODE_TERMS.search(r["instruction"])]


def test_simplification_rows_are_not_trivia(produced):
    train, validation, _ = produced
    simplification = [r for r in train + validation if r["task_category"] == "simplification"]
    assert not [r["id"] for r in simplification if _TRIVIA.search(r["instruction"])]
    assert all(r["input"] for r in simplification)


def test_classification_answers_are_labels_offered_in_the_instruction(produced):
    train, validation, _ = produced
    classification = [r for r in train + validation if r["task_category"] == "classification"]
    offenders = [r["id"] for r in classification if normalize(r["output"]) not in normalize(r["instruction"])]
    assert offenders == []


def test_no_degenerate_outputs(produced):
    train, validation, _ = produced
    assert [r["id"] for r in train + validation if is_degenerate_output(r["output"])] == []


def test_no_duplicate_content_within_or_across_splits(produced):
    train, validation, _ = produced
    triples = Counter((normalize(r["instruction"]), normalize(r["input"]), normalize(r["output"])) for r in train + validation)
    assert [t for t, n in triples.items() if n > 1] == []
    train_pairs = {(normalize(r["instruction"]), normalize(r["input"])) for r in train}
    val_pairs = {(normalize(r["instruction"]), normalize(r["input"])) for r in validation}
    assert train_pairs.isdisjoint(val_pairs)


def test_no_overlap_with_frozen_evaluation_prompts(produced):
    train, validation, _ = produced
    keys = _load_eval_prompt_keys(DATA_DIR / "eval")
    for r in train + validation:
        assert (normalize(r["instruction"]), normalize(r["input"])) not in keys.pairs, r["id"]
        assert normalize(_combined_text(r)) not in keys.prompts, r["id"]


def test_totals_and_per_category_minimum_or_warning(produced):
    train, validation, report = produced
    total = len(train) + len(validation)
    assert TARGET_TOTAL_MIN <= total <= TARGET_TOTAL_MAX
    counts = Counter(r["task_category"] for r in train + validation)
    for category in TASK_CATEGORIES:
        if counts[category] < MIN_PER_CATEGORY:
            assert any(w.startswith(f"{category}:") for w in report["warnings"]), category


def test_report_fingerprints_match_files(produced):
    from src.run_manifest import sha256_of

    _, _, report = produced
    for path, digest in report["fingerprints"].items():
        assert sha256_of(Path(path)) == digest, path
